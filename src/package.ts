/**
 * Pack everything the print shop needs into one ZIP:
 * `chanukia-lemon/stl/*.stl` (print files), `PRINT-SHOP.md` in three languages,
 * `LICENSE`, `NOTICE`, and links to the website and the GitHub repository
 * (`LINKS.txt` plus `Website.url` / `GitHub.url` shortcuts that open with a double click).
 *
 * Usage: `node src/package.ts [out_dir]` (after `node src/build.ts`)
 *
 * @module
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PRINT_PARTS } from './assembly.ts';
import { AUTHOR, PROJECT, REPO_URL, SITE_URL } from './credits.ts';
import { OUT_DIR, PRINT_ZIP, ROOT } from './paths.ts';
import { zip } from './zip.ts';
import type { ZipEntry } from './zip.ts';

/** Top folder inside the archive. */
const FOLDER = 'chanukia-lemon';
/** Repository files shipped with the models (instructions are generated by `npm run docs`). */
const DOCS = [
  'PRINT-SHOP.md',
  'PRINT-SHOP.ru.md',
  'PRINT-SHOP.he.md',
  'LICENSE-MODELS.md',
  'LICENSE',
  'NOTICE',
];

const stlEntry =
  (outDir: string) =>
  ({ file }: { file: string }): ZipEntry => ({
    name: `${FOLDER}/stl/${file}.stl`,
    data: readFileSync(join(outDir, `${file}.stl`)),
  });

const docEntry = (name: string): ZipEntry => ({
  name: `${FOLDER}/${name}`,
  data: readFileSync(join(ROOT, name)),
});

/** Internet shortcut (Windows `.url`; also opened by most macOS/Linux file managers). */
const shortcut = (name: string, url: string): ZipEntry => ({
  name: `${FOLDER}/${name}`,
  data: Buffer.from(`[InternetShortcut]\r\nURL=${url}\r\n`, 'utf8'),
});

/** Plain-text links in the three documentation languages. */
const LINKS_TXT = [
  `${PROJECT} by ${AUTHOR}`,
  '',
  `Website / Сайт / אתר: ${SITE_URL}`,
  `Source code / Исходный код / קוד מקור (GitHub): ${REPO_URL}`,
  '',
].join('\n');

const linkEntries = (): ZipEntry[] => [
  { name: `${FOLDER}/LINKS.txt`, data: Buffer.from(LINKS_TXT, 'utf8') },
  shortcut('Website.url', SITE_URL),
  shortcut('GitHub.url', REPO_URL),
];

function main(outDir: string): void {
  const entries = [...DOCS.map(docEntry), ...linkEntries(), ...PRINT_PARTS.map(stlEntry(outDir))];
  const archive = zip(entries);
  const path = join(outDir, PRINT_ZIP);
  writeFileSync(path, archive);
  console.log(`${path}: ${entries.length} files, ${(archive.length / 1e6).toFixed(1)} MB`);
}

main(process.argv[2] ?? OUT_DIR);
